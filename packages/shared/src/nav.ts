export const COMMAND_CENTRE: NavModule = {
  key: "command-centre",
  label: "Event Operations",
  path: "/",
  phase: 1,
  built: true,
  features: feat("Event Pack", "Live Readiness", "Cross-module Board", "Activity Feed"),
};

export function findModuleByPath(path: string): NavModule | undefined {
  if (path === COMMAND_CENTRE.path) return COMMAND_CENTRE;
  return NAV.flatMap((group) => group.modules).find((mod) => mod.path === path);
}

export function findFeature(path: string, featureKey: string | null): NavFeature | undefined {
  if (!featureKey) return undefined;
  return findModuleByPath(path)?.features.find((feature) => feature.key === featureKey);
}
