/**
 * Sidebar IA — Section 5 of the master build prompt.
 * Feature lists are Section 4 scope, used in-page, not as extra sidebar items.
 */
export interface NavFeature {
  key: string;
  label: string;
}

export interface NavModule {
  key: string;
  label: string;
  path: string;
  phase: 1 | 2 | 3 | 4 | 5;
  built: boolean;
  features: NavFeature[];
}

export interface NavGroup {
  key: string;
  label: string;
  modules: NavModule[];
}

function feat(...labels: string[]): NavFeature[] {
  return labels.map((label) => ({
    key: label
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, ""),
    label,
  }));
}

